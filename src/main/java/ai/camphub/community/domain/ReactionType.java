package ai.camphub.community.domain;

/**
 * 互动类型。
 *
 * <p>点赞与收藏合并成一张 {@code post_reaction} 表、用一个类型列区分，而不是两张表。
 * 理由是两者的<b>结构与生命周期完全一致</b>（都是"某人对某帖的一种态度"，
 * 都是幂等的、都可随时取消），拆成两张表只会让每处逻辑都写两遍。
 *
 * <p>枚举名与数据库中的字符串值一一对应，由 MyBatis 默认的枚举处理器按名称映射。
 * 遇到未登记的值会直接抛异常，而不是悄悄落回某个默认值 —— 这是刻意的：
 * 一个拼错的 {@code LIKES} 应该在写入时就失败，而不是变成一条查不出来的互动记录。
 */
public enum ReactionType {

    /** 点赞。 */
    LIKE,

    /** 收藏（加入"我的收藏"列表）。 */
    FAVORITE
}
