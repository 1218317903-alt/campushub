package ai.camphub.platform.audit.domain;

/**
 * 审计结果。
 *
 * <p>只有两个取值，且<b>失败也必须落库</b> —— 这一点是审计与普通业务日志的关键区别：
 * 业务日志关心"发生了什么"，审计关心"谁试图做了什么、成没成"。
 * 如果只记录成功操作，那么"有人在 10 分钟内尝试了 5000 次登录"这类最有价值的信号
 * 恰好全部丢失。
 */
public enum AuditResult {

    /** 操作成功完成。 */
    SUCCESS,

    /** 操作被拒绝或失败。 */
    FAILURE
}
