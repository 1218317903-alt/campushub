package ai.camphub.workspace.app;

import ai.camphub.workspace.domain.ParsedDocument;

/**
 * 文档解析端口：把一份字节流变成带结构的段落。
 *
 * <h2>为什么是一个端口加多个实现，而不是一个 switch</h2>
 * 三种格式的解析逻辑没有任何共同点：PDF 要解压内容流、解析字体编码、重排文本位置；
 * Markdown 要识别标题层级；纯文本只是解码。把它们塞进一个方法里的 {@code switch}，
 * 结果是那个方法同时是"格式分派"、"PDF 解析"和"编码处理"三件事的所在地，
 * 而新增一种格式意味着修改一个已经很长的既存方法（而不是添加一个文件）。
 *
 * <p>端口 + 实现之后，"支持哪些格式"由容器里注册了哪些实现决定，
 * 而"能不能处理这个 MIME"就是每个实现自己回答的问题（{@link #supports(String)}）。
 *
 * <h2>为什么签名里没有输出上下文（文档 ID、存储键）</h2>
 * 解析器只做一件事：字节 → 段落。它不需要知道这些段属于哪份文档，
 * 也不做任何数据库或存储访问。这条约束是有价值的：解析逻辑因此可以
 * 脱离数据库与容器单独构造并测试（{@code PdfDocumentParserTest} 就是这么做的），
 * 而"解析器在解析过程中偷偷删了一行数据"这种事在类型上就不可能发生。
 *
 * <h2>实现必须自己保证的两件事</h2>
 * <ol>
 *   <li><b>不关闭传入的流</b>。流的生命周期由调用方管理 ——
 *       解析器在自己的方法里关掉它，会让调用方在解析之后无法再读取（例如算哈希）。</li>
 *   <li><b>不无界地消耗内存与时间</b>。输入是不可信的用户文件，
 *       解析期间的内存与时间都必须有上界（页面数、解压后的流大小、超时）。
 *       这不是"尽力而为"的建议，而是这个端口存在的格式安全性要求。</li>
 * </ol>
 */
public interface DocumentParser {

    /**
     * 是否能处理这个内容类型。
     *
     * <p>比较必须忽略大小写与参数（{@code text/markdown; charset=utf-8} 与
     * {@code TEXT/MARKDOWN} 是同一个类型）。分派由调用方按注册顺序进行，
     * 因此同一个类型只应有一个实现声明支持。
     *
     * @param mimeType 内容类型，调用方已归一化为小写且去掉参数
     * @return 支持时为 true
     */
    boolean supports(String mimeType);

    /**
     * 解析内容。
     *
     * <h2>为什么接 {@code byte[]} 而不是 {@code InputStream}</h2>
     * 三种格式的解析库全都需要内容的随机访问或整体长度：PDF 要建可寻址的
     * 随机读取缓冲，文本与 Markdown 要先解码（而编码探测必须先看到全部字节，
     * 否则 BOM 与非法序列的判定都无从做起）。给一个流只会让每个实现各自
     * 先调一次 {@code readAllBytes}，把同一件事做三遍。
     *
     * <p>更重要的是：<b>读取上限的校验因此只在一个地方做</b>。
     * 流一旦进入解析器，调用方就再也无法约束它被读了多少字节；
     * 而 {@code byte[]} 在进入之前就已经被检查过长度。这是"内存上界"
     * 这条要求能被验证的唯一形态 —— 否则它只是每个实现里一句注释。
     *
     * @param content 完整内容；调用方已保证其长度不超过配置上限
     * @return 解析产出
     * @throws DocumentParseException 解析失败；异常自带"是否值得重试"的判定
     */
    ParsedDocument parse(byte[] content);

    /**
     * 解析器版本标识，写入 {@code document.parser_version}。
     *
     * <p>它必须能区分行为有差异的两次实现 —— 因此带上底层库的版本
     * （如 {@code pdfbox-3.0.7}），而不是一个业务侧的语义化版本号。
     * 这里要回答的问题是"同一份字节，用不同版本的解析器会不会得到不同的文本"，
     * 而那是底层库决定的。
     *
     * @return 版本标识，长度不超过 {@code document.parser_version VARCHAR(32)}
     */
    String version();
}
