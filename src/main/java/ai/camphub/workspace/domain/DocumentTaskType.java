package ai.camphub.workspace.domain;

/**
 * 文档任务类型。
 *
 * <h2>为什么需要 CLEANUP，而不是"删除时顺手删字节"</h2>
 * 删除文档时同时做两件事：标记元数据行删除、删除存储里的字节。它们不在同一个事务里
 * （字节不在数据库中，无法参与回滚），因此必然存在一个窗口 —— 元数据已经标记删除，
 * 而字节还没被删掉。
 *
 * <p>在这个窗口里进程崩溃，字节就永久留在存储上，且库里没有任何线索指向它：
 * {@code document.deleted_at} 已经填了，看起来这次删除是完整的。
 * 把"删字节"变成一条有状态、可重试的任务之后，这个窗口里的失败会被记下来并自动重试，
 * 而不是消失在一次无人观察的崩溃里。
 *
 * <p>本项目的删除是<b>软删除</b>（{@code deleted_at}），所以 {@code storage_key}
 * 在删除后仍然留在行上 —— 它既是 CLEANUP 任务的输入，也是"字节尚未清理"的标志。
 * 清理成功后它被置为 NULL，这件事才算真的做完。
 */
public enum DocumentTaskType {

    /**
     * 解析：抽取正文文本并切分成可检索的分块。
     *
     * <p>入队时机是上传成功时（同一个本地事务），失败可按退避策略重试。
     */
    PARSE,

    /**
     * 清理：把已经软删除的文档的字节从存储里真正删掉。
     *
     * <p>入队时机是删除请求已经提交之后。<b>它的失败不需要让用户感知</b> ——
     * 用户看到的是"文档已删除"，那是事实；剩下的只是空间回收，
     * 可以慢慢重试，重试到上限后留在表里等排查。
     */
    CLEANUP
}
