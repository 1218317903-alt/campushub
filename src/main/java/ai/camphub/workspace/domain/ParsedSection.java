package ai.camphub.workspace.domain;

/**
 * 解析得到的一段内容，带它所属的标题路径。
 *
 * <h2>为什么输出的是"带标题的段"而不是一整块文本</h2>
 * 分块要按语义边界切，而"语义边界"唯一真实可用的信号就是文档自己的结构。
 * 如果解析器只吐一整块文本，切分器就只能按字符数硬切 —— 那会把一个列表
 * 切成两半、把一个函数签名与它的说明分开。
 *
 * <p>三种格式都能提供这个信号，只是来源不同：
 * <ul>
 *   <li>Markdown：标题行本身就是结构，标题路径由层级拼出（"部署 > 环境要求"）。</li>
 *   <li>PDF：没有标题层级可依赖，但<b>页码</b>有 —— 它就是"第 3 页"。
 *       这不是形式上的对齐：用户拿着检索结果去找原文时，第一个问题就是"在第几页"。</li>
 *   <li>纯文本：没有结构。{@code heading} 为 null，整篇按段落切。</li>
 * </ul>
 *
 * @param heading 所属标题路径，可为 null（无结构时）
 * @param text    该段的正文
 */
public record ParsedSection(String heading, String text) {
}
