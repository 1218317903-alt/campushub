-- ==========================================================================
-- V4 : 修正 schema 基线标记（Phase 03 收尾）
-- ==========================================================================
-- 纪律：V1 / V2 / V3 已应用，禁止再改。
--
-- 背景：V1 在 app_metadata 里写入了 ('schema.baseline', 'V1')，
-- /api/v1/system/info 读取它作为"迁移是否生效"的判据。
-- 但 V2（identity）与 V3（community）都没有跟着更新这一行 ——
-- 于是库结构已经到 V3，接口仍然报 V1。
--
-- 为什么这一点必须修：该端点的用途就是"部署后一个请求就能确认服务已起、且迁移已生效"
-- （docs/architecture.md §6.3）。一个恒为 V1 的值不但做不到这件事，
-- 还会给出一个**看起来正常**的错误结论 —— 比字段缺失更难发现。
--
-- 为什么单开一个迁移，而不是改 V3：
--   V3 已经被应用（flyway_schema_history 里有它）。虽然本阶段尚未打 tag，
--   但"已应用即不可变"是更安全的习惯 —— 依赖"还没发布所以可以改"这条理由，
--   会在某次忘记重建本地库时以一个难懂的校验错误的形式失效。
--
-- 语义在此明确（此前只是隐含）：**该值等于"已应用到的最新迁移版本号"**，
--   因此每个新增迁移都应当把本行更新为它自己的版本号。
--   SystemInfoIT 会断言"标记值 == 迁移脚本里的最大版本号"，
--   所以"加了迁移却忘了更新本行"会直接让构建失败，而不是静默漂移。
-- ==========================================================================

UPDATE app_metadata
SET meta_value = 'V4'
WHERE meta_key = 'schema.baseline';
